def language_options() -> tuple[tuple[str, str], ...]:
    return tuple((code, LANGUAGE_NAMES[code]) for code in LANGUAGE_NAMES)


def normalize_language(value: object) -> str:
    code = str(value or DEFAULT_LANGUAGE).strip()
    return code if code in LANGUAGE_NAMES else DEFAULT_LANGUAGE


def translate(language: object, key: str, **kwargs: object) -> str:
    language_code = normalize_language(language)
    text = _TRANSLATIONS.get(language_code, {}).get(key)
    if text is None:
        text = _TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key)
    if not kwargs:
        return text
    return text.format(**kwargs)
